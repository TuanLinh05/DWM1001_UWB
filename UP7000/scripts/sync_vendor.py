"""Copy the UWB telemetry parser into the UP4000 ROS 2 package.

The package must be self-contained on the drone, but the protocol has one
source of truth: Software/UWB_UART_GUI. Run this after changing either file;
test_vendor_sync.py fails while the copies differ.

python UP7000/scripts/sync_vendor.py
"""
from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "Software" / "UWB_UART_GUI"
TARGET = REPO / "UP7000" / "ros2_ws" / "src" / "uwb_px4_logger" / "uwb_px4_logger" / "vendor"
FILES = ("telemetry_protocol.py", "burst_metadata.py")
HEADER = "# GENERATED by UP7000/scripts/sync_vendor.py from Software/UWB_UART_GUI/{name}. Do not edit.\n"


def vendored_text(name: str) -> str:
    text = (SOURCE / name).read_text(encoding="utf-8")
    # Package-relative import; the only change to the source.
    text = text.replace("import telemetry_protocol as tp", "from . import telemetry_protocol as tp")
    return HEADER.format(name=name) + text


def main() -> None:
    TARGET.mkdir(parents=True, exist_ok=True)
    (TARGET / "__init__.py").write_text('"""Vendored copies; see scripts/sync_vendor.py."""\n',
                                       encoding="utf-8", newline="\n")
    for name in FILES:
        (TARGET / name).write_text(vendored_text(name), encoding="utf-8", newline="\n")
        print(f"synced {name}")


if __name__ == "__main__":
    main()
